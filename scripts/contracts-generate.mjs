#!/usr/bin/env node
// Generates the runtime schema objects and TypeScript types that the rest of the
// repository imports. `schemas/**` and `openapi/openapi.yaml` are the only sources; this
// script is the only writer of `packages/contracts/src/generated`.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve as resolvePath } from 'node:path';
import process from 'node:process';
import { fileURLToPath, URL } from 'node:url';
import { compile } from 'json-schema-to-typescript';
import SwaggerParser from '@apidevtools/swagger-parser';
import openapiTS, { astToString } from 'openapi-typescript';
import * as prettier from 'prettier';

export const HEADER = '// GENERATED by scripts/contracts-generate.mjs — do not edit.';

const DEFAULT_OUT = 'packages/contracts/src/generated';
const DEFAULT_SCHEMAS_DIR = 'schemas';
const DEFAULT_OPENAPI = 'openapi/openapi.yaml';

const MERCHANT_EVENT_SCHEMA = 'webhooks/merchant-event.v1.schema.json';

function parseArgs(argv) {
  const options = {
    out: DEFAULT_OUT,
    schemasDir: DEFAULT_SCHEMAS_DIR,
    openapi: DEFAULT_OPENAPI,
  };
  const flags = { '--out': 'out', '--schemas-dir': 'schemasDir', '--openapi': 'openapi' };
  for (let index = 0; index < argv.length; index += 1) {
    const flag = argv[index];
    const key = flags[flag];
    if (key === undefined) continue;
    const value = argv[index + 1];
    if (value === undefined) throw new Error(`${flag} requires a value`);
    options[key] = value;
    index += 1;
  }
  return options;
}

/** Every `*.schema.json` under the schemas directory, as paths relative to it, sorted. */
function collectSchemaPaths(schemasDir) {
  const found = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.name.endsWith('.schema.json')) found.push(relative(schemasDir, full));
    }
  };
  walk(schemasDir);
  return found.map((p) => p.split('\\').join('/')).sort();
}

/** Replaces component-schema refs with $defs refs, for a standalone components document. */
function rewriteRefs(node) {
  if (Array.isArray(node)) return node.map(rewriteRefs);
  if (node !== null && typeof node === 'object') {
    const out = {};
    for (const [key, value] of Object.entries(node)) {
      out[key] =
        typeof value === 'string'
          ? value.split('#/components/schemas/').join('#/$defs/')
          : rewriteRefs(value);
    }
    return out;
  }
  return node;
}

/** Every `x-` key anywhere inside a subtree, deduplicated and sorted. */
function collectExtensionKeywords(node, acc = new Set()) {
  if (Array.isArray(node)) {
    for (const item of node) collectExtensionKeywords(item, acc);
  } else if (node !== null && typeof node === 'object') {
    for (const [key, value] of Object.entries(node)) {
      if (key.startsWith('x-')) acc.add(key);
      collectExtensionKeywords(value, acc);
    }
  }
  return acc;
}

const DECLARATION = /^export (?:interface|type|const|enum|declare) (\w+)/;

/** Splits a compiled schema into top-level declaration blocks keyed by exported name. */
function splitDeclarations(source) {
  const blocks = [];
  let current = null;
  for (const line of source.split('\n')) {
    const match = DECLARATION.exec(line);
    if (match !== null) {
      if (current !== null) blocks.push(current);
      current = { name: match[1], lines: [line] };
    } else if (current !== null) {
      current.lines.push(line);
    }
  }
  if (current !== null) blocks.push(current);
  return blocks.map((block) => ({
    name: block.name,
    text: block.lines.join('\n').replace(/\s+$/, ''),
  }));
}

/**
 * json-schema-to-typescript cannot resolve an external file ref that carries a fragment
 * (`../common/x.schema.json#/$defs/y`), and every FlowLedger message composes one. These
 * schemas contain no reference cycles, so external refs are inlined before compiling and
 * internal `#/...` refs are left alone for the compiler to handle.
 */
function pointerGet(root, fragment) {
  if (fragment === '') return root;
  const parts = fragment
    .replace(/^#/, '')
    .split('/')
    .filter((part) => part !== '')
    .map((part) => part.replace(/~1/g, '/').replace(/~0/g, '~'));
  let node = root;
  for (const part of parts) {
    if (node === null || typeof node !== 'object' || !(part in node)) {
      throw new Error(`unresolvable $ref fragment: ${fragment}`);
    }
    node = node[part];
  }
  return node;
}

function inlineExternalRefs(node, baseDir, cache, depth = 0) {
  if (depth > 64) throw new Error('$ref nesting exceeded 64 levels');
  if (Array.isArray(node))
    return node.map((item) => inlineExternalRefs(item, baseDir, cache, depth + 1));
  if (node === null || typeof node !== 'object') return node;
  if (typeof node.$ref === 'string' && !node.$ref.startsWith('#')) {
    const [filePart, fragment = ''] = node.$ref.split('#');
    const absolute = resolvePath(baseDir, filePart);
    const target = cache.get(absolute) ?? JSON.parse(readFileSync(absolute, 'utf8'));
    cache.set(absolute, target);
    return inlineExternalRefs(
      pointerGet(target, `#${fragment}`),
      dirname(absolute),
      cache,
      depth + 1,
    );
  }
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    out[key] = inlineExternalRefs(value, baseDir, cache, depth + 1);
  }
  return out;
}

/**
 * Message-local `$defs` keys are generic (`data`), so compiled on their own every message
 * would export a type called `Data` and the dedupe below would collapse them into one
 * wrong shared type. Local definitions are therefore prefixed with the message name.
 */
function messagePrefix(schema, fallbackPath) {
  const id = typeof schema.$id === 'string' ? schema.$id : fallbackPath;
  const base = id.split('/').pop() ?? fallbackPath;
  return (
    base
      .replace(/\.schema\.json$/, '')
      .split(/[^A-Za-z0-9]+/)
      .filter((part) => part !== '')
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join('') || 'Message'
  );
}

/**
 * Every message schema declares a local `$defs` (usually just `data`), so compiled as-is
 * they all export a type literally called `Data` and the dedupe step collapses them into
 * one wrong shared type. Local definitions are renamed with a message-specific prefix and
 * the message's own `#/$defs/...` refs are repointed.
 */
function namespaceLocalDefs(document, prefix) {
  const defs = document.$defs;
  if (defs === null || typeof defs !== 'object') return document;

  const renamed = new Map();
  const namespaced = {};
  for (const [key, value] of Object.entries(defs)) {
    const nextKey = `${prefix}${key.charAt(0).toUpperCase()}${key.slice(1)}`;
    renamed.set(`#/$defs/${key}`, `#/$defs/${nextKey}`);
    namespaced[nextKey] = value;
  }

  const rewrite = (node) => {
    if (Array.isArray(node)) return node.map(rewrite);
    if (node === null || typeof node !== 'object') return node;
    const out = {};
    for (const [key, value] of Object.entries(node)) {
      out[key] =
        typeof value === 'string' && renamed.has(value) ? renamed.get(value) : rewrite(value);
    }
    return out;
  };

  const rewritten = rewrite(document);
  rewritten.$defs = namespaced;
  return rewritten;
}

/** Fails loudly rather than silently emitting `unknown` for a ref that cannot resolve. */
function assertRefsResolve(document, label) {
  const walk = (node, path) => {
    if (Array.isArray(node)) {
      node.forEach((item, index) => walk(item, `${path}/${index}`));
      return;
    }
    if (node === null || typeof node !== 'object') return;
    for (const [key, value] of Object.entries(node)) {
      if (key === '$ref' && typeof value === 'string' && value.startsWith('#')) {
        try {
          pointerGet(document, value);
        } catch {
          throw new Error(`${label}: unresolved internal $ref ${value} at ${path}`);
        }
      } else {
        walk(value, `${path}/${key}`);
      }
    }
  };
  walk(document, '');
}

/**
 * Config is resolved from the repository root, never from the output directory: resolving
 * beside `out` made the bytes depend on where the output went, so generating into a temp
 * directory for the drift check produced different formatting from the committed tree.
 */
const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url));

async function format(source, parser) {
  const config = (await prettier.resolveConfig(join(REPO_ROOT, 'package.json'))) ?? {};
  return prettier.format(source, { ...config, parser });
}

function json(value) {
  return JSON.stringify(value, null, 2);
}

export async function generate(options) {
  const { out, schemasDir, openapi } = { ...parseArgs([]), ...options };

  const schemaPaths = collectSchemaPaths(schemasDir);
  const jsonSchemas = schemaPaths.map((path) => ({
    path,
    schema: JSON.parse(readFileSync(join(schemasDir, path), 'utf8')),
  }));
  const registry = JSON.parse(readFileSync(join(schemasDir, 'registry.v1.json'), 'utf8'));
  const registeredTypes = registry.messages.map((message) => message.type);

  const schemasSource = [
    HEADER,
    '',
    `export const jsonSchemas = ${json(jsonSchemas)} as const;`,
    '',
    `export const registry = ${json(registry)} as const;`,
    '',
    `export const registeredTypes = ${json(registeredTypes)} as const;`,
    '',
    'export type MessageType = (typeof registeredTypes)[number];',
    '',
  ].join('\n');

  const document = await SwaggerParser.parse(openapi);
  const componentSchemas = document.components?.schemas ?? {};
  const extensionKeywords = [...collectExtensionKeywords(componentSchemas)].sort();
  const componentsSource = [
    HEADER,
    '',
    `export const openApiComponentsSchema = ${json({
      $id: 'https://flowledger.dev/openapi/components.json',
      $defs: rewriteRefs(componentSchemas),
    })} as const;`,
    '',
    `export const openApiExtensionKeywords = ${json(extensionKeywords)} as const;`,
    '',
  ].join('\n');

  const messagePaths = [
    ...new Set([...registry.messages.map((message) => message.schema), MERCHANT_EVENT_SCHEMA]),
  ].sort();
  const seen = new Set();
  const blocks = [];
  const refCache = new Map();
  for (const path of messagePaths) {
    const sourcePath = join(schemasDir, path);
    const inlined = inlineExternalRefs(
      JSON.parse(readFileSync(sourcePath, 'utf8')),
      dirname(sourcePath),
      refCache,
    );
    const prefix = messagePrefix(inlined, path);
    const namespaced = namespaceLocalDefs(inlined, prefix);
    assertRefsResolve(namespaced, path);
    const compiled = await compile(namespaced, namespaced.title ?? path, {
      bannerComment: '',
      additionalProperties: false,
      strictIndexSignatures: true,
      unreachableDefinitions: false,
    });
    for (const block of splitDeclarations(compiled)) {
      if (seen.has(block.name)) continue;
      seen.add(block.name);
      blocks.push(block.text);
    }
  }
  const messagesSource = [HEADER, '', blocks.join('\n\n'), ''].join('\n');

  const openapiSource = [HEADER, '', astToString(await openapiTS(document)), ''].join('\n');

  const files = new Map([
    ['schemas.ts', await format(schemasSource, 'typescript')],
    ['openapi-components.ts', await format(componentsSource, 'typescript')],
    ['messages.ts', await format(messagesSource, 'typescript')],
    ['openapi.ts', await format(openapiSource, 'typescript')],
  ]);

  mkdirSync(out, { recursive: true });
  for (const [name, contents] of files) writeFileSync(join(out, name), contents);

  return { out, files };
}

const isMain = process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const options = parseArgs(process.argv.slice(2));
  const { out, files } = await generate({
    out: options.out,
    schemasDir: options.schemasDir,
    openapi: options.openapi,
  });
  process.stdout.write(`generated ${files.size} files into ${out}\n`);
}
